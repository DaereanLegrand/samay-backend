#!/usr/bin/env bash
# =============================================================================
# secrets.sh — ONE implementation of "which values are generated, and how",
# for both kinds of environment this project has.
#
#   --file <path>            the local stack env file (ENV=testing-local).
#                            Generated in place with openssl/uuidgen. The vault
#                            is never contacted.
#   --vault <app> <env>      a vault profile (ENV=testing|staging|prod).
#                            Delegates to the vault broker's owner-only `regen`
#                            verb over SSH. One GPG pinentry prompt.
#
# Both targets expose the SAME unit vocabulary, in the same order, and the same
# report shape, so `make init` and `make regen` behave identically apart from
# where the bytes land:
#
#   unit            generated keys
#   supabase-jwt    JWT_SECRET + SUPABASE_ANON_KEY + SUPABASE_SERVICE_ROLE_KEY
#   rustfs          RUSTFS_ACCESS_KEY + RUSTFS_SECRET_KEY
#   realtime        REALTIME_SECRET_KEY_BASE
#   admin-api-key   ADMIN_API_KEY                     (vault only)
#   admin-uuid      SYSTEM_ADMIN_USER_ID
#   const           supabase-url + apple-bundle-id     (vault only)
#
# Everything else is either a DEPLOYMENT FACT (ports, URLs, toggles) or a FIXED
# credential (Google/Apple ids+secrets, SMTP password, FCM/Play service
# accounts, RevenueCat keys, repo token). Those are never generated by
# definition, and every one of them is named in the report so nothing is
# silently left behind.
#
# Verbs:
#   init   ensure every generated value exists; never replaces an existing one.
#   regen  replace values (all units, or the ones named). Always asks first.
#
# Usage:
#   secrets.sh init  --file  <path>
#   secrets.sh init  --vault <app> <env>
#   secrets.sh regen --file  <path>  [--yes] [unit...]
#   secrets.sh regen --vault <app> <env> [--yes] [unit...]
#
# Exit: 0 ok · 1 a required value is missing / a generation failed · 2 usage.
# =============================================================================
set -uo pipefail

SELF_DIR="$(cd "$(dirname "$0")" && pwd)"

ALL_UNITS=(supabase-jwt rustfs realtime admin-api-key admin-uuid const)
FILE_UNITS=(supabase-jwt rustfs realtime admin-uuid)
VAULT_UNITS=(supabase-jwt rustfs realtime admin-api-key admin-uuid const)

usage() {
  sed -n '3,40p' "$0" | sed 's/^# \{0,1\}//'
  exit 2
}

say()  { printf '%s\n' "$*"; }
warn() { printf '%s\n' "$*" >&2; }

# ── argument parsing ────────────────────────────────────────────────────────
VERB="${1:-}"; shift 2>/dev/null || true
case "$VERB" in init|regen) ;; *) usage ;; esac

TARGET=""
APP=""; ENV_NAME=""
case "${1:-}" in
  --file)  TARGET=file;  FILE_PATH="${2:-}"; shift 2 2>/dev/null || true ;;
  --vault) TARGET=vault; APP="${2:-}"; ENV_NAME="${3:-}"; shift 3 2>/dev/null || true ;;
  *) usage ;;
esac

ASSUME_YES=0
UNITS=()
for a in "$@"; do
  case "$a" in
    --yes|-y) ASSUME_YES=1 ;;
    -*) warn "secrets: unknown flag '$a'"; exit 2 ;;
    *) UNITS+=("$a") ;;
  esac
done

case "$TARGET" in
  file)
    [ -n "$FILE_PATH" ] || usage
    VALID_UNITS=("${FILE_UNITS[@]}")
    ;;
  vault)
    [ -n "$APP" ] && [ -n "$ENV_NAME" ] || usage
    case "$ENV_NAME" in testing|staging|prod) ;; *) warn "secrets: env must be testing|staging|prod (got '$ENV_NAME')"; exit 2 ;; esac
    VALID_UNITS=("${VAULT_UNITS[@]}")
    ;;
esac

if [ "${#UNITS[@]}" -eq 0 ]; then
  UNITS=("${VALID_UNITS[@]}")
else
  for u in "${UNITS[@]}"; do
    case " ${VALID_UNITS[*]} " in
      *" $u "*) ;;
      *) warn "secrets: unit '$u' does not exist for --$TARGET (known: ${VALID_UNITS[*]})"; exit 2 ;;
    esac
  done
fi

have() { command -v "$1" >/dev/null 2>&1; }
confirm() { # confirm <prompt>
  if [ "$ASSUME_YES" = "1" ]; then say "$1 [--yes]"; return 0; fi
  have gum || { warn "secrets: gum is required to confirm (or pass --yes)"; return 1; }
  [ -t 0 ] || { warn "secrets: confirmation needs a terminal (or pass --yes)"; return 1; }
  gum confirm --default=false "$1" --affirmative="Proceed" --negative="Cancel"
}

# ═════════════════════════════════════════════════════════════════════════════
# FILE TARGET — the local stack env file (ENV=testing-local)
# ═════════════════════════════════════════════════════════════════════════════
file_generated_keys() { # unit → keys
  case "$1" in
    supabase-jwt) printf 'JWT_SECRET SUPABASE_ANON_KEY SUPABASE_SERVICE_ROLE_KEY' ;;
    rustfs)       printf 'RUSTFS_ACCESS_KEY RUSTFS_SECRET_KEY' ;;
    realtime)     printf 'REALTIME_SECRET_KEY_BASE' ;;
    admin-uuid)   printf 'SYSTEM_ADMIN_USER_ID' ;;
  esac
}

# Credentials this environment cannot mint. Google's client ids are PUBLIC and
# live in the tracked example; its SECRET and Apple's are console-issued. The
# FCM/Play service accounts and the RevenueCat keys are provider-issued. The
# admin UUID is the one identity the operator picks.
file_fixed() {
  cat <<'EOF'
GOTRUE_EXTERNAL_GOOGLE_SECRET GOTRUE_EXTERNAL_APPLE_SECRET
SUPABASE_FCM_SERVICE_ACCOUNT_JSON_B64 REVENUECAT_WEBHOOK_SECRET
REVENUECAT_API_KEY REVENUECAT_PROJECT_ID SAMAY_ADMIN_USER_ID
EOF
}

cmd_file() {
  local mode=--fill
  [ "$VERB" = "regen" ] && mode=--force

  if [ ! -f "$FILE_PATH" ] && [ "$VERB" = "regen" ]; then
    warn "secrets: $FILE_PATH does not exist — run 'make init' first."
    return 1
  fi

  # Ask BEFORE touching anything, and say truthfully what is at stake.
  local what
  if [ "$VERB" = "regen" ]; then
    what="regenerate ${UNITS[*]} in $FILE_PATH"
  else
    what="create any missing generated value in $FILE_PATH"
  fi
  confirm "This will $what. The vault is not contacted." || { say "cancelled"; return 1; }

  local out rc
  # Both tools live in this repo, so a standalone clone needs nothing else.
  local minter="$SELF_DIR/gen-local-env.sh"
  [ -x "$minter" ] || { warn "secrets: file minter not found: $minter"; return 1; }
  out="$(bash "$minter" "$FILE_PATH" "$mode" "${UNITS[@]}" 2>&1)"
  rc=$?
  printf '%s\n' "$out"
  [ "$rc" -eq 0 ] || { warn "secrets: generation failed"; return 1; }

  # ── report ────────────────────────────────────────────────────────────────
  # The minter already printed the generated keys and any unit it skipped; this
  # adds the part it cannot know: which credentials are NOT generatable at all.
  say ""
  local fixed_missing=()
  local f
  for f in $(file_fixed); do
    [ -n "$(sed -n "s/^$f=//p" "$FILE_PATH" | head -1 | tr -d '\"')" ] || fixed_missing+=("$f")
  done
  say "fixed credentials (never generated): $(file_fixed | tr '\n' ' ' | xargs)"
  if [ "${#fixed_missing[@]}" -gt 0 ]; then
    say ""
    warn "not regenerated — these are FIXED and must be supplied by hand:"
    printf '  %s\n' "${fixed_missing[@]}" >&2
  fi

  # A regenerated JWT secret must also reach the RUNNING database: jwt.sql only
  # runs at volume creation, so app.settings.jwt_secret would otherwise keep the
  # previous generation. Apply it when the stack is up; say so when it is not.
  case "$out" in
    *"generated JWT_SECRET"*)
      local port db
      port="$(sed -n 's/^POSTGRES_PORT=//p' "$FILE_PATH" | head -1 | tr -d '"')"
      db="$(sed -n 's/^STACK_PREFIX=//p' "$FILE_PATH" | head -1 | tr -d '"')-db"
      if docker ps --format '{{.Names}}' | grep -qx "$db"; then
        say "applying the new JWT secret to the running database ($db)"
        docker exec "$db" psql -U supabase_admin -d postgres -q -c \
          "ALTER DATABASE postgres SET \"app.settings.jwt_secret\" TO '$(sed -n 's/^JWT_SECRET=//p' "$FILE_PATH" | head -1)';" \
          >/dev/null && say "database secret updated (restart the stack to be safe)" \
          || warn "WARN: could not update app.settings.jwt_secret in $db"
      else
        warn "note: stack not running — app.settings.jwt_secret will be set on next \`make reset\`"
      fi
      ;;
  esac
  return 0
}

# ═════════════════════════════════════════════════════════════════════════════
# VAULT TARGET — testing | staging | prod (broker `check` + `regen`)
# ═════════════════════════════════════════════════════════════════════════════
select_vault_host() {
  local h host
  for h in ${VAULT_HOSTS:-${VAULT_HOST:-vault@laptop-local vault@laptop}}; do
    host="$(ssh -G "$h" 2>/dev/null | awk '/^hostname /{print $2; exit}')"
    [ -n "$host" ] || host="${h#*@}"
    if nc -z -G 3 "$host" 22 >/dev/null 2>&1; then printf '%s\n' "$h"; return 0; fi
  done
  return 1
}

cmd_vault() {
  local vh report
  vh="$(select_vault_host)" || { warn "secrets: no vault host reachable"; return 1; }
  say "vault host: $vh (app=$APP env=$ENV_NAME)"

  # Read-only presence report: never decrypts, so it works before the passphrase.
  report="$(ssh -T "$vh" "check $APP $ENV_NAME")" || { warn "secrets: broker check failed"; return 1; }

  local missing_fixed
  missing_fixed="$(printf '%s\n' "$report" | awk -F'\t' '($1=="fixed"||$1=="shared")&&$2=="missing"{print $4}')"
  if [ -n "$missing_fixed" ]; then
    warn "secrets: FIXED entries are missing — these cannot be generated; insert them on the vault host:"
    printf '  pass insert -m %s\n' $missing_fixed >&2
    return 1
  fi

  local sel=()
  if [ "$VERB" = "init" ]; then
    # init only fills what is absent; never replaces a live value.
    local mu
    mu="$(printf '%s\n' "$report" | awk -F'\t' '{
      if ($2=="missing" && $1=="gen") print $3;
      else if ($2=="missing" && $1=="const") print "const";
    }' | sort -u)"
    if [ -z "$mu" ]; then
      say "nothing missing — profile already complete"
      report_vault "$report" "$vh"
      return 0
    fi
    for u in $mu; do case " ${VALID_UNITS[*]} " in *" $u "*) sel+=("$u") ;; esac; done
    say "missing generated entries fill these units: ${sel[*]}"
  else
    sel=("${UNITS[@]}")
  fi

  [ "${#sel[@]}" -gt 0 ] || { report_vault "$report" "$vh"; return 0; }

  confirm "This will make a change on the vault ($APP/$ENV_NAME: ${sel[*]}). Proceed?" \
    || { say "cancelled"; return 1; }

  # shellcheck disable=SC2086
  ssh -t "$vh" "regen $APP $ENV_NAME ${sel[*]}" || { warn "secrets: regen failed"; return 1; }

  report="$(ssh -T "$vh" "check $APP $ENV_NAME")" || true
  report_vault "$report" "$vh"
  return 0
}

report_vault() { # report_vault <check-output> <vault-host>
  local report="$1"
  local n_facts n_fixed n_gen
  n_facts="$(printf '%s\n' "$report" | awk -F'\t' '$1=="const"||$1=="shared"{c++} END{print c+0}')"
  n_fixed="$(printf '%s\n' "$report" | awk -F'\t' '$1=="fixed"{c++} END{print c+0}')"
  n_gen="$(printf '%s\n' "$report" | awk -F'\t' '$1=="gen"{c++} END{print c+0}')"
  say ""
  say "generated entries:        $n_gen"
  say "fixed credentials (never generated): $n_fixed"
  say "deployment facts:         $n_facts"
  local still
  still="$(printf '%s\n' "$report" | awk -F'\t' '$2=="missing"{print $4}')"
  if [ -n "$still" ]; then
    warn ""
    warn "not regenerated (still missing) — these need a human:"
    printf '  %s\n' $still >&2
    return 1
  fi
  return 0
}

# ── dispatch ────────────────────────────────────────────────────────────────
case "$TARGET" in
  file)  cmd_file ;;
  vault) cmd_vault ;;
esac
