ALTER TABLE public.notifications
    ADD COLUMN IF NOT EXISTS category text,
    ADD COLUMN IF NOT EXISTS push_allowed boolean DEFAULT true NOT NULL;

UPDATE public.notifications
   SET category = public.notification_category(type)
 WHERE category IS NULL;

ALTER TABLE public.notifications
    ALTER COLUMN category SET DEFAULT 'other';

CREATE INDEX IF NOT EXISTS idx_notifications_push_allowed
    ON public.notifications USING btree (push_sent_at, category)
    WHERE push_sent_at IS NULL AND push_allowed;

-- ---------------------------------------------------------------------------
-- Mutes (Q4b). Mute is one-way and weaker than block: the muted user may still
-- DM the muter, but their activity is removed from the muter's notifications,
-- feed and rankings. The table lives here because insert_notification() reads
-- it; the RPC surface is in 04_blocks_mutes.sql.
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.user_mutes (
    muter_id uuid NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    muted_id uuid NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    created_at timestamp with time zone DEFAULT now() NOT NULL,
    CONSTRAINT user_mutes_pkey PRIMARY KEY (muter_id, muted_id),
    CONSTRAINT user_mutes_distinct CHECK (muter_id <> muted_id)
);

ALTER TABLE public.user_mutes ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.user_mutes FORCE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS user_mutes_own ON public.user_mutes;
CREATE POLICY user_mutes_own ON public.user_mutes
    FOR SELECT USING (muter_id = auth.uid());

REVOKE ALL ON TABLE public.user_mutes FROM anon;
REVOKE INSERT, UPDATE, DELETE ON TABLE public.user_mutes FROM authenticated;
GRANT SELECT ON TABLE public.user_mutes TO authenticated;
GRANT ALL ON TABLE public.user_mutes TO service_role;

CREATE INDEX IF NOT EXISTS idx_user_mutes_muted ON public.user_mutes (muted_id);
CREATE INDEX IF NOT EXISTS idx_user_mutes_muter ON public.user_mutes (muter_id);

-- ---------------------------------------------------------------------------
-- insert_notification — the single write path. Signature is unchanged so the
-- existing triggers keep working; the body adds preference + block/mute gates.
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.insert_notification(
    p_user_id uuid,
    p_type text,
    p_title text,
    p_body text,
    p_data jsonb DEFAULT NULL::jsonb
) RETURNS void
    LANGUAGE plpgsql SECURITY DEFINER
    SET search_path TO ''
    AS $$
DECLARE
    v_category text := public.notification_category(p_type);
    v_actor uuid;
    v_actor_raw text;
BEGIN
    -- Spam guard: non-privileged callers may only notify themselves.
    IF current_user NOT IN ('service_role', 'postgres', 'supabase_admin')
       AND auth.uid() IS DISTINCT FROM p_user_id THEN
        RAISE EXCEPTION 'Not authorized';
    END IF;

    -- Preference gate. A disabled category is not stored at all (so it cannot
    -- reach the in-app center or the push worker).
    IF NOT public.notification_enabled(p_user_id, p_type) THEN
        RETURN;
    END IF;

    -- Block/mute gate for user-generated activity. Security, moderation and
    -- legal notices are never suppressed: a blocked/muted user's report
    -- outcome must still reach the recipient.
    IF v_category NOT IN ('security', 'moderation', 'legal', 'other') THEN
        v_actor_raw := COALESCE(
            p_data ->> 'actorId',
            p_data ->> 'senderId',
            p_data ->> 'userId',
            p_data ->> 'requesterId',
            p_data ->> 'invitedById'
        );
        IF v_actor_raw ~* '^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$' THEN
            v_actor := v_actor_raw::uuid;
            IF v_actor <> p_user_id THEN
                IF public.is_blocked_between(p_user_id, v_actor) THEN
                    RETURN;
                END IF;
                IF EXISTS (
                    SELECT 1 FROM public.user_mutes
                     WHERE muter_id = p_user_id AND muted_id = v_actor
                ) THEN
                    RETURN;
                END IF;
            END IF;
        END IF;
    END IF;

    INSERT INTO public.notifications
        (user_id, type, title, body, data, category, push_allowed)
    VALUES
        (p_user_id, p_type, p_title, p_body, p_data, v_category, true);
END;
$$;

REVOKE ALL ON FUNCTION public.insert_notification(uuid, text, text, text, jsonb) FROM PUBLIC;
GRANT ALL ON FUNCTION public.insert_notification(uuid, text, text, text, jsonb) TO service_role;

-- ---------------------------------------------------------------------------
-- The message notification now carries the sender so the block/mute gate can
-- suppress it (shared group/event content follows the same rule — membership is
-- untouched, only the notification is hidden).
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.notify_new_message() RETURNS trigger
    LANGUAGE plpgsql SECURITY DEFINER
    SET search_path TO ''
    AS $$
DECLARE
    v_recipient uuid;
    v_chat_type public.chat_type;
    v_reference_id uuid;
BEGIN
    SELECT type, reference_id INTO v_chat_type, v_reference_id
    FROM public.chats WHERE id = NEW.chat_id;
    IF NOT FOUND THEN RETURN NEW; END IF;

    IF v_chat_type = 'direct' THEN
        FOR v_recipient IN
            SELECT user_id FROM public.chat_participants WHERE chat_id = NEW.chat_id
        LOOP
            IF v_recipient <> NEW.sender_id THEN
                PERFORM public.insert_notification(
                    v_recipient, 'new_message', 'Nuevo mensaje',
                    'Tienes un nuevo mensaje en el chat',
                    jsonb_build_object(
                        'chatId', NEW.chat_id,
                        'senderId', NEW.sender_id,
                        'actorId', NEW.sender_id));
            END IF;
        END LOOP;
    ELSIF v_chat_type = 'group' THEN
        FOR v_recipient IN
            SELECT user_id FROM public.group_members
            WHERE group_id = v_reference_id AND status = 'active'
        LOOP
            IF v_recipient <> NEW.sender_id THEN
                PERFORM public.insert_notification(
                    v_recipient, 'new_message', 'Nuevo mensaje',
                    'Tienes un nuevo mensaje en el chat',
                    jsonb_build_object(
                        'chatId', NEW.chat_id,
                        'senderId', NEW.sender_id,
                        'actorId', NEW.sender_id));
            END IF;
        END LOOP;
    ELSIF v_chat_type = 'event' THEN
        FOR v_recipient IN
            SELECT user_id FROM public.event_invites
            WHERE event_id = v_reference_id AND status <> 'declined'
            UNION
            SELECT user_id FROM public.event_hosts
            WHERE event_id = v_reference_id
        LOOP
            IF v_recipient <> NEW.sender_id THEN
                PERFORM public.insert_notification(
                    v_recipient, 'new_message', 'Nuevo mensaje',
                    'Tienes un nuevo mensaje en el chat',
                    jsonb_build_object(
                        'chatId', NEW.chat_id,
                        'senderId', NEW.sender_id,
                        'actorId', NEW.sender_id));
            END IF;
        END LOOP;
    END IF;
    RETURN NEW;
END;
$$;

-- Event invites carry the inviter for the block gate.
CREATE OR REPLACE FUNCTION public.notify_event_invite() RETURNS trigger
    LANGUAGE plpgsql SECURITY DEFINER
    SET search_path TO ''
    AS $$
DECLARE
    v_event_name text;
BEGIN
    SELECT name INTO v_event_name FROM public.events WHERE id = NEW.event_id;
    PERFORM public.insert_notification(
        NEW.user_id,
        'event_invite',
        'Invitación a evento',
        COALESCE(v_event_name, 'Tienes una invitación a un evento'),
        jsonb_build_object(
            'eventId', NEW.event_id,
            'invitedById', NEW.invited_by_user_id,
            'actorId', NEW.invited_by_user_id)
    );
    RETURN NEW;
END;
$$;

-- Minigame invites carry the creator/initiator.
CREATE OR REPLACE FUNCTION public.notify_minigame_invite() RETURNS trigger
    LANGUAGE plpgsql SECURITY DEFINER
    SET search_path TO ''
    AS $$
DECLARE
    v_recipient uuid;
    v_actor uuid := CASE WHEN array_length(NEW.participants, 1) >= 1
                         THEN NEW.participants[1] ELSE NULL END;
BEGIN
    FOREACH v_recipient IN ARRAY NEW.participants
    LOOP
        PERFORM public.insert_notification(
            v_recipient,
            'minigame_invite',
            'Invitación a minijuego',
            'Te invitaron a un minijuego de grupo',
            jsonb_build_object(
                'groupId', NEW.group_id,
                'sessionId', NEW.id,
                'actorId', v_actor)
        );
    END LOOP;
    RETURN NEW;
END;
$$;

-- ---------------------------------------------------------------------------
-- Group invites (group_members.status='invited') were silent before. The
-- inviter is auth.uid() at insert time; staff/host-created and self-created
-- invites both land here. The notification respects the `friends` category and
-- the block gate above.
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.notify_group_invite() RETURNS trigger
    LANGUAGE plpgsql SECURITY DEFINER
    SET search_path TO ''
    AS $$
DECLARE
    v_group_name text;
    v_actor uuid := auth.uid();
BEGIN
    IF NEW.status <> 'invited' THEN
        RETURN NEW;
    END IF;
    IF TG_OP = 'UPDATE' AND OLD.status = 'invited' THEN
        RETURN NEW;
    END IF;

    SELECT name INTO v_group_name FROM public.groups WHERE id = NEW.group_id;
    PERFORM public.insert_notification(
        NEW.user_id,
        'group_invite',
        'Invitación a grupo',
        COALESCE(v_group_name, 'Te invitaron a un grupo'),
        jsonb_build_object(
            'groupId', NEW.group_id,
            'invitedById', v_actor,
            'actorId', v_actor)
    );
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS notify_group_invite_trigger ON public.group_members;
CREATE TRIGGER notify_group_invite_trigger
    AFTER INSERT OR UPDATE OF status ON public.group_members
    FOR EACH ROW
    WHEN (NEW.status = 'invited')
    EXECUTE FUNCTION public.notify_group_invite();

REVOKE ALL ON FUNCTION public.notify_group_invite() FROM PUBLIC;

