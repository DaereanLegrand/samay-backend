-- ============================================================================
-- 234_safety_moderation / 01_notification_preferences.sql
--
-- Q4a (2026-10-23): notification categories are SERVER-persisted. The client
-- no longer owns the preference contract (the old Flutter screen wrote a local
-- Hive cache only). One JSON object per user on `users.notification_preferences`
-- with these categories:
--
--   chat, events, friends, minigames  -> default ON
--   marketing                         -> default OFF
--   security, moderation, legal       -> always delivered, not user-toggleable
--
-- Enforcement is at the notification WRITE boundary (`insert_notification`):
-- a disabled category never creates an in-app row, so it can never be pushed
-- either. `notifications.push_allowed` is the explicit contract the Go push
-- worker filters on (defence in depth: rows inserted by service_role directly
-- still carry the flag), and the worker only pushes the narrow type allow-list.
--
-- Also enforced here:
--   * block/mute hide the actor's notifications (except security/moderation/
--     legal outcomes, which must always reach the user);
--   * group-invite notifications are generated by a trigger and respect the
--     `friends` category.
--
-- Rollback:
--   DROP FUNCTION public.set_notification_preferences(jsonb);
--   DROP FUNCTION public.get_notification_preferences();
--   ... and restore the 110_notifications insert_notification() body. Keep the
--   notifications.category/push_allowed columns (dropping them would break the
--   push worker's filter); forward-fix only.
--
-- Backfill: existing users with `{}` get the defaults in one UPDATE. Existing
-- notifications get category='other' (always delivered) and push_allowed=true.
-- Locking: the UPDATE touches every user row; run it in a maintenance window on
-- large deployments (or split by id ranges). The migration is idempotent.
-- ============================================================================

-- ---------------------------------------------------------------------------
-- Category mapping + defaults. Unknown/new types are 'other' and always
-- delivered so a server-side addition can never disappear silently.
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.notification_category(p_type text)
RETURNS text
    LANGUAGE sql IMMUTABLE
    SET search_path TO ''
    AS $$
    SELECT CASE
        WHEN p_type IN ('new_message', 'message', 'message_received', 'chat') THEN 'chat'
        WHEN p_type IN (
            'event_invite', 'event_cancelled', 'event_live', 'event_reminder',
            'attendance_confirmed', 'feature_request'
        ) THEN 'events'
        WHEN p_type IN (
            'friend_request', 'friend_accepted', 'group_invite', 'group_joined'
        ) THEN 'friends'
        WHEN p_type LIKE 'minigame%' THEN 'minigames'
        WHEN p_type LIKE 'marketing%' OR p_type IN ('promotion', 'promo') THEN 'marketing'
        WHEN p_type IN (
            'security', 'security_alert', 'login_alert', 'password_changed',
            'new_device'
        ) THEN 'security'
        WHEN p_type IN (
            'report_outcome', 'moderation_action', 'ban', 'ban_appeal',
            'appeal_outcome', 'moderation'
        ) THEN 'moderation'
        WHEN p_type IN ('legal', 'terms_update', 'privacy_update') THEN 'legal'
        ELSE 'other'
    END;
$$;

CREATE OR REPLACE FUNCTION public.notification_preference_defaults()
RETURNS jsonb
    LANGUAGE sql IMMUTABLE
    SET search_path TO ''
    AS $$
    SELECT jsonb_build_object(
        'chat', true,
        'events', true,
        'friends', true,
        'minigames', true,
        'marketing', false,
        'security', true,
        'moderation', true,
        'legal', true
    );
$$;

-- Always-delivered categories: a user can store a `false`, but the server
-- ignores it.
CREATE OR REPLACE FUNCTION public.notification_category_locked(p_category text)
RETURNS boolean
    LANGUAGE sql IMMUTABLE
    SET search_path TO ''
    AS $$
    SELECT p_category IN ('security', 'moderation', 'legal', 'other');
$$;

CREATE OR REPLACE FUNCTION public.normalize_notification_preferences(p_prefs jsonb)
RETURNS jsonb
    LANGUAGE plpgsql IMMUTABLE
    SET search_path TO ''
    AS $$
DECLARE
    v_out jsonb := public.notification_preference_defaults();
    v_key text;
    v_val jsonb;
BEGIN
    IF p_prefs IS NULL OR jsonb_typeof(p_prefs) <> 'object' THEN
        RETURN v_out;
    END IF;

    FOR v_key, v_val IN SELECT key, value FROM jsonb_each(p_prefs)
    LOOP
        IF v_key IN ('chat', 'events', 'friends', 'minigames', 'marketing') THEN
            IF jsonb_typeof(v_val) <> 'boolean' THEN
                RAISE EXCEPTION 'invalid_preferences'
                    USING ERRCODE = 'P0001',
                          DETAIL = format('preference %s must be a boolean', v_key);
            END IF;
            v_out := jsonb_set(v_out, ARRAY[v_key], v_val, true);
        ELSIF NOT public.notification_category_locked(v_key) THEN
            RAISE EXCEPTION 'invalid_preferences'
                USING ERRCODE = 'P0001',
                      DETAIL = format('unknown notification category: %s', v_key);
        END IF;
    END LOOP;

    -- Locked categories always read true, whatever was sent.
    v_out := jsonb_set(v_out, '{security}', 'true'::jsonb, true);
    v_out := jsonb_set(v_out, '{moderation}', 'true'::jsonb, true);
    v_out := jsonb_set(v_out, '{legal}', 'true'::jsonb, true);
    RETURN v_out;
END;
$$;

REVOKE ALL ON FUNCTION public.notification_category(text) FROM PUBLIC;
REVOKE ALL ON FUNCTION public.notification_preference_defaults() FROM PUBLIC;
REVOKE ALL ON FUNCTION public.notification_category_locked(text) FROM PUBLIC;
REVOKE ALL ON FUNCTION public.normalize_notification_preferences(jsonb) FROM PUBLIC;

-- ---------------------------------------------------------------------------
-- Read/write RPCs. Both act on auth.uid() only — there is no "read somebody
-- else's preferences" surface.
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.get_notification_preferences()
RETURNS jsonb
    LANGUAGE plpgsql SECURITY DEFINER
    SET search_path TO ''
    AS $$
DECLARE
    v_uid uuid := auth.uid();
    v_prefs jsonb;
BEGIN
    IF v_uid IS NULL THEN
        RAISE EXCEPTION 'not_authenticated' USING ERRCODE = 'P0001';
    END IF;
    SELECT notification_preferences INTO v_prefs
      FROM public.users WHERE id = v_uid;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'user_not_found' USING ERRCODE = 'P0001';
    END IF;
    RETURN public.normalize_notification_preferences(v_prefs);
END;
$$;

CREATE OR REPLACE FUNCTION public.set_notification_preferences(p_prefs jsonb)
RETURNS jsonb
    LANGUAGE plpgsql SECURITY DEFINER
    SET search_path TO ''
    AS $$
DECLARE
    v_uid uuid := auth.uid();
    v_norm jsonb;
BEGIN
    IF v_uid IS NULL THEN
        RAISE EXCEPTION 'not_authenticated' USING ERRCODE = 'P0001';
    END IF;
    IF p_prefs IS NULL OR jsonb_typeof(p_prefs) <> 'object' THEN
        RAISE EXCEPTION 'invalid_preferences' USING ERRCODE = 'P0001';
    END IF;

    v_norm := public.normalize_notification_preferences(p_prefs);

    UPDATE public.users
       SET notification_preferences = v_norm,
           updated_at = now()
     WHERE id = v_uid;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'user_not_found' USING ERRCODE = 'P0001';
    END IF;

    RETURN v_norm;
END;
$$;

REVOKE ALL ON FUNCTION public.get_notification_preferences() FROM PUBLIC, anon;
REVOKE ALL ON FUNCTION public.set_notification_preferences(jsonb) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.get_notification_preferences() TO authenticated, service_role;
GRANT EXECUTE ON FUNCTION public.set_notification_preferences(jsonb) TO authenticated, service_role;

CREATE OR REPLACE FUNCTION public.notification_enabled(p_user_id uuid, p_type text)
RETURNS boolean
    LANGUAGE plpgsql STABLE SECURITY DEFINER
    SET search_path TO ''
    AS $$
DECLARE
    v_cat text := public.notification_category(p_type);
    v_prefs jsonb;
    v_default jsonb;
    v_value jsonb;
BEGIN
    IF public.notification_category_locked(v_cat) THEN
        RETURN true;
    END IF;
    SELECT notification_preferences INTO v_prefs
      FROM public.users WHERE id = p_user_id;
    IF NOT FOUND THEN
        RETURN true;
    END IF;
    v_default := public.notification_preference_defaults();
    v_value := COALESCE(v_prefs -> v_cat, v_default -> v_cat, 'true'::jsonb);
    RETURN COALESCE((v_value)::text::boolean, true);
END;
$$;

REVOKE ALL ON FUNCTION public.notification_enabled(uuid, text) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.notification_enabled(uuid, text) TO service_role;

